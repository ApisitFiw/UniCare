  result = result.replace(/คะแนนเฉลี่ย\s*10\s*ข้อย่อย\s*\(([0-9.]+)\s*ดาว\)/g, "10-criteria average ($1 stars)");
  result = result.replace(/ต่างกัน\s*([0-9.]+)\s*ดาว/g, "differs by $1 stars");
  result = result.replace(/ปรับดาวภาพรวมเป็น\s*(\d+)\s*ดาว/g, "Harmonize overall to $1 stars");
  result = result.replace(/ปรับ\s*10\s*ข้อเป็น\s*(\d+)\s*ดาว/g, "Harmonize 10 criteria to $1 stars");

  // Dynamic counts and units (secondary)
  result = result.replace(/(\d+)\s*รายการ/g, "$1 items");
  result = result.replace(/(\d+)\s*เรื่อง/g, "$1 cases");
  result = result.replace(/(\d+)\s*คน/g, "$1 people");
