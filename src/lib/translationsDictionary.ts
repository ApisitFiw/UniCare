  result = result.replace(/(\d+)\s*รายการในระบบติดตาม/g, "$1 reports in tracking system");
  result = result.replace(/(\d+)\s*เรื่องในระบบติดตาม/g, "$1 reports in tracking system");
  result = result.replace(/ชั้น\s*([0-9ST]+|ลอย|ใต้ดิน)/g, "Floor $1");
  result = result.replace(/ห้อง\s*([A-Za-z0-9]+)/g, "Room $1");
  result = result.replace(/หอพัก\s*(\d+)/g, "Dormitory $1");
  result = result.replace(/หอพักลักษณานิเวศ\s*(\d+)/g, "Lakshananivet Dormitory $1");
  result = result.replace(/อาคารเรียนรวม\s*(\d+)/g, "Academic Complex $1");
